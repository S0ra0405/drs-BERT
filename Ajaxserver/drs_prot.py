def predict_Sentence_attr(vec):
  """
  ベクトル化された1文を学習済みBERTモデルを使用して要素分類を行う。

   与えられたベクトルをモデルに入力し、"claim","ground","undifine"に分類し、返す。

  Args:
    vec (touch.Tensor): モデルに入力するベクトル化された文
  
  Returns:
    str: 予測されたクラス名("claim","ground","undifine")
  """
  model = BertForSequenceClassification.from_pretrained('../data/model_transformers_Element_classification_forMaC')
  model.eval()  

  with torch.no_grad():
    outputs = model(vec)
    logits = outputs.logits
    predicted_class = torch.argmax(logits, dim=1).item()
  
  class_map = {
    0: 'claim',
    1: 'ground',
    2: 'ground'
  }
  prediction = class_map.get(predicted_class, 'undifine')

  return prediction

def make_vec(sentence):
  """
  トークナイザを用いた文のベクトル化

  Args:
    sentence (str): ベクトル化を行う対象の1文

  Returns: 
    touch.Tensor: バッチサイズ１のテンソル形式で、トークンIDが格納されている。

  """
  input_ids = tokenizer.encode(sentence, add_special_tokens=True)
  input_ids = torch.tensor(input_ids).unsqueeze(0) 
  return input_ids

def make_vec_2sentences(first_sentence, second_sentence):
  """
  トークナイザを用いた2文のベクトル化

  2文をまとめてベクトル化

  Args: 
    first_sentence (str): ベクトル化を行う2文のうち1分目
    second_sentence (str): ベクトル化を行う2文のうち2文目

  Returns:
    touch.Tensor: バッチサイズ1のテンソル形式で、トークンIDが格納されている。
  """
  input_ids = tokenizer.encode(first_sentence,second_sentence,add_special_tokens=True)
  input_ids = torch.tensor(input_ids).unsqueeze(0)  # バッチサイズ1で入力
  return input_ids

