#文章を文単位で分割
def parse_Paragraph(paragraph):
    """
    文章を文単位に分割し、リストとして返す。

    Returns:
      list[str]:  句点で終わる文のリスト
    """
    if not re.search(r'[。．]\s?|\. ?|$', paragraph):
        paragraph += '。'
    sentences = re.split(r'(?:。|．|\. ?|$)', paragraph)
    # 空白や空文字だけの要素を除外し、句点を補う
    res = [s.strip() + '。' for s in sentences if s.strip()]
    return res

def parse_Sentence(sentence):
  """
  MeCabを使用して1文を分かち書き

  Returns: MeCabが形態素解析した結果を文字列として返す。
          品詞情報が含まれる。
  """  
  m = MeCab.Tagger()  
  parsed = m.parse(sentence)
  return parsed

def parse_Parag_to_Word(paragraph):
  """
  MeCabを使用して文章を分かち書き

  Returns: MeCabが文章を形態素解析した結果を文字列のリストとして返す。
            品詞情報が含まれる。
  """
  sentences = parse_Paragraph(paragraph)
  word_parsed_paragraph = [[p.split('\t') for p in parse_Sentence(s).split('\n')[:-2]] for s in sentences]
  return word_parsed_paragraph


